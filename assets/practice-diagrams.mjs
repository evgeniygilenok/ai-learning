// Teaching diagrams for the local practice product. Schemas are reading aids,
// not additional runtime types or completed learner evidence.
const node = (title, detail, owner) => ({ title, detail, owner });
const flow = (label, ...nodes) => ({ kind: "flow", label, nodes });
const schema = (label, fields) => ({ kind: "schema", label, fields });
const compare = (label, ...nodes) => ({ kind: "compare", label, nodes });
const diagram = (title, caption, ...groups) => ({ title, caption, groups });

